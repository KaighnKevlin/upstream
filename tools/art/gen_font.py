def panel():
    """Brass frame, rivets in the corners, translucent dark inside."""
    from clockwork import Figure, BRONZE, DARK, STEEL
    fig = Figure()
    fig.box((-12, -12, 12, 12), BRONZE, z=0, bevel=2.5)
    fig.box((-8.5, -8.5, 8.5, 8.5), DARK, z=1, bevel=1.0, grit=0.0)
    for x in (-10, 10):
        for y in (-10, 10):
            fig.sphere((x, y), 1.0, STEEL, z=2)
    img = fig.render(24, 24, (12, 12), outline=False)
    for y in range(7, 17):
        for x in range(7, 17):
            p = img[y][x]
            img[y][x] = p[:3] + (205,)
    return img


def arrow():
    """Off-screen enemy marker: brass chevron pointing right, cyan core."""
    from clockwork import Figure, BRONZE, GLOW
    fig = Figure()
    fig.capsule((-5, -6), (4, 0), 1.8, BRONZE, z=0)
    fig.capsule((-5, 6), (4, 0), 1.8, BRONZE, z=0)
    fig.sphere((-3, 0), 2.2, GLOW, z=1, emissive=True)
    return fig.render(18, 18, (9, 9))


def main():
    import os
    out = os.path.join(os.path.dirname(__file__), '../../assets/ui')
    os.makedirs(out, exist_ok=True)
    W, H = 16 * CW, 6 * CH
    img = [[(0, 0, 0, 0)] * W for _ in range(H)]
    for code in range(32, 128):
        g = G.get(chr(code))
        if g is None:
            continue
        cx, cy = (code - 32) % 16 * CW, (code - 32) // 16 * CH
        for y, row in enumerate(g):
            for x, ch in enumerate(row):
                if ch == '#':
                    img[cy + y][cx + x] = (255, 255, 255, 255)
    write_png(out + '/font.png', W, H, img)
    write_png(out + '/panel.png', 24, 24, panel())
    write_png(out + '/arrow.png', 18, 18, arrow())
    missing = [chr(c) for c in range(33, 127) if chr(c) not in G]
    print('wrote assets/ui/font.png; no glyph for:', ''.join(missing))


if __name__ == '__main__':
    main()
